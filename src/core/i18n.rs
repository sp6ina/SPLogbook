use serde::{Deserialize, Serialize};

/// Moduł z tabelą tłumaczeń `tr` (wydzielony ze względu na rozmiar).
#[path = "i18n_tr.rs"]
mod i18n_tr;
pub use i18n_tr::tr;

/// Obsługiwane języki w programie SPLogbook
/// Dodano obsługę języków: Niemiecki (DE), Francuski (FR) oraz Hiszpański (ES)
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[derive(Default)]
pub enum Language {
    #[serde(rename = "pl")]
    #[default]
    Pl,
    #[serde(rename = "en")]
    En,
    #[serde(rename = "de")]
    De,
    #[serde(rename = "fr")]
    Fr,
    #[serde(rename = "es")]
    Es,
    #[serde(rename = "ru")]
    Ru,
}

impl Language {
    pub fn code(&self) -> &'static str {
        match self {
            Language::Pl => "pl",
            Language::En => "en",
            Language::De => "de",
            Language::Fr => "fr",
            Language::Es => "es",
            Language::Ru => "ru",
        }
    }

    pub fn display_name(&self) -> &'static str {
        match self {
            Language::Pl => "Polski",
            Language::En => "English",
            Language::De => "Deutsch",
            Language::Fr => "Français",
            Language::Es => "Español",
            Language::Ru => "Русский",
        }
    }

    pub fn from_code(code: &str) -> Self {
        match code.to_lowercase().as_str() {
            "en" | "en_us" | "en_gb" => Language::En,
            "de" | "de_de" | "de_at" | "de_ch" => Language::De,
            "fr" | "fr_fr" | "fr_be" | "fr_ca" => Language::Fr,
            "es" | "es_es" | "es_mx" => Language::Es,
            "ru" | "ru_ru" => Language::Ru,
            _ => Language::Pl,
        }
    }
}

// Funkcje pomocnicze dla poszczególnych języków
pub fn translate_pl(key: &str) -> &str { tr(key, Language::Pl) }
pub fn translate_en(key: &str) -> &str { tr(key, Language::En) }
pub fn translate_de(key: &str) -> &str { tr(key, Language::De) }
pub fn translate_fr(key: &str) -> &str { tr(key, Language::Fr) }
pub fn translate_es(key: &str) -> &str { tr(key, Language::Es) }
pub fn translate_ru(key: &str) -> &str { tr(key, Language::Ru) }

