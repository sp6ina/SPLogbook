/// Wyszukuje modele radiostacji po nazwie, producencie lub identyfikatorze
pub fn search_rig_models(query: &str) -> Vec<&'static RigModelInfo> {
    let q = query.trim().to_uppercase();
    if q.is_empty() {
        return ALL_RIG_MODELS.iter().collect();
    }
    ALL_RIG_MODELS
        .iter()
        .filter(|r| {
            r.mfg.to_uppercase().contains(&q)
                || r.model.to_uppercase().contains(&q)
                || r.rig_id.to_string().contains(&q)
        })
        .collect()
}

/// Zwraca listę unikalnych producentów
pub fn get_all_manufacturers() -> Vec<&'static str> {
    let mut mfgs: Vec<&'static str> = ALL_RIG_MODELS.iter().map(|r| r.mfg).collect();
    mfgs.sort_unstable();
    mfgs.dedup();
    mfgs
}

/// Wyszukuje konkretny model po rig_id
pub fn find_rig_by_id(rig_id: u32) -> Option<&'static RigModelInfo> {
    ALL_RIG_MODELS.iter().find(|r| r.rig_id == rig_id)
}

